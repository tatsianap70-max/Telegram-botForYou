#!/bin/bash
# ==============================================================================
# ENTRYPOINT ДЛЯ ДЕПЛОЯ НА AMVERA
# ==============================================================================
#
# Этот скрипт запускается при каждом старте контейнера на Amvera.
# Выполняет три этапа:
#   1. Проверка кода — пытается импортировать приложение
#   2. Миграции — применяет изменения схемы базы данных
#   3. Запуск — стартует uvicorn сервер
#
# При ошибке на любом этапе:
#   - Скрипт останавливается (благодаря set -e)
#   - Отправляется уведомление в Telegram (если настроен LOGGING__TELEGRAM__CHAT_ID)
#   - Контейнер падает — Amvera покажет ошибку в логах
#
# Переменные окружения для уведомлений:
#   BOT__TOKEN                  — токен бота (уже есть для работы бота)
#   LOGGING__TELEGRAM__CHAT_ID  — Telegram ID админа для уведомлений
#
# Как узнать свой Telegram ID:
#   1. Напишите боту @userinfobot в Telegram
#   2. Он ответит вашим ID (число вида 123456789)
# ==============================================================================

# При ошибке в любой команде — остановить скрипт
# pipefail нужен, чтобы ошибки в первой части пайпа (например alembic | tee)
# не терялись и корректно приводили к падению деплоя.
set -eo pipefail

# ==============================================================================
# ФУНКЦИЯ ЭКРАНИРОВАНИЯ HTML
# ==============================================================================
#
# Экранирует специальные символы HTML для безопасной вставки в сообщения.
# Telegram использует HTML parse_mode, поэтому символы <, >, & в тексте ошибок
# (например, в Python traceback: File "<string>") сломают парсинг.
#
# Параметры:
#   $1 — текст для экранирования
#
# Возвращает:
#   Экранированный текст через echo (используйте $(...) для захвата)
#
# Пример:
#   escaped=$(escape_html "File <stdin>")  # -> "File &lt;stdin&gt;"
# ==============================================================================
escape_html() {
    local text="$1"
    # Порядок важен: & должен экранироваться первым,
    # иначе &lt; превратится в &amp;lt;
    text="${text//&/&amp;}"
    text="${text//</&lt;}"
    text="${text//>/&gt;}"
    echo "$text"
}

# ==============================================================================
# ФУНКЦИЯ ОТПРАВКИ УВЕДОМЛЕНИЯ В TELEGRAM
# ==============================================================================
#
# Отправляет сообщение админу через Telegram Bot API.
# Использует curl для HTTP-запроса к api.telegram.org.
#
# Параметры:
#   $1 — текст сообщения (поддерживает emoji и переносы строк)
#
# Зависимости:
#   - BOT__TOKEN — токен бота (обязательно для работы бота)
#   - LOGGING__TELEGRAM__CHAT_ID — ID чата админа (опционально)
#
# Если LOGGING__TELEGRAM__CHAT_ID не указан — функция ничего не делает.
# Это позволяет запускать бота без настройки уведомлений.
# ==============================================================================
send_telegram_notification() {
    local message="$1"

    # Если ID админа не указан — просто выходим без ошибки
    # Уведомления опциональны, бот должен работать и без них
    if [ -z "$LOGGING__TELEGRAM__CHAT_ID" ]; then
        echo "[Уведомления] LOGGING__TELEGRAM__CHAT_ID не указан, пропускаем отправку"
        return 0
    fi

    # Если токен бота не указан — это критическая ошибка конфигурации
    # Но мы не падаем, просто логируем предупреждение
    if [ -z "$BOT__TOKEN" ]; then
        echo "[Уведомления] BOT__TOKEN не указан, невозможно отправить уведомление"
        return 0
    fi

    # Отправляем сообщение через Telegram Bot API
    # --silent — не показывать прогресс загрузки
    # --show-error — но показывать ошибки
    # --max-time 10 — таймаут 10 секунд (чтобы не зависнуть при проблемах с сетью)
    # parse_mode=HTML — поддержка <b>, <i>, <code> в тексте
    #
    # Если curl завершится с ошибкой — игнорируем (|| true)
    # Уведомление не должно блокировать запуск приложения
    curl --silent --show-error --max-time 10 \
        -X POST "https://api.telegram.org/bot${BOT__TOKEN}/sendMessage" \
        -d "chat_id=${LOGGING__TELEGRAM__CHAT_ID}" \
        -d "text=${message}" \
        -d "parse_mode=HTML" > /dev/null 2>&1 || true

    echo "[Уведомления] Отправлено уведомление админу"
}

# ==============================================================================
# ФУНКЦИЯ ОТПРАВКИ ФАЙЛА В TELEGRAM
# ==============================================================================
#
# Отправляет файл с полным текстом ошибки, если сообщение слишком длинное.
#
# Параметры:
#   $1 — содержимое файла
#   $2 — имя файла
# ==============================================================================
send_telegram_file() {
    local content="$1"
    local filename="$2"

    if [ -z "$LOGGING__TELEGRAM__CHAT_ID" ] || [ -z "$BOT__TOKEN" ]; then
        return 0
    fi

    # Создаём временный файл
    local tmpfile=$(mktemp)
    echo "$content" > "$tmpfile"

    # Отправляем файл
    curl --silent --show-error --max-time 30 \
        -X POST "https://api.telegram.org/bot${BOT__TOKEN}/sendDocument" \
        -F "chat_id=${LOGGING__TELEGRAM__CHAT_ID}" \
        -F "document=@${tmpfile};filename=${filename}" > /dev/null 2>&1 || true

    # Удаляем временный файл
    rm -f "$tmpfile"

    echo "[Уведомления] Отправлен файл с полным логом"
}

# ==============================================================================
# ЭТАП 1: ПРОВЕРКА КОДА
# ==============================================================================
#
# Пытаемся импортировать главный модуль приложения.
# Это проверяет:
#   - Синтаксис Python-кода (нет SyntaxError)
#   - Все импорты работают (нет ImportError, ModuleNotFoundError)
#   - Все зависимости установлены
#   - Конфигурация валидна (pydantic проверяет .env при импорте settings)
#
# Если импорт упал — значит код точно не запустится.
# Лучше узнать об этом сразу, чем после применения миграций.
# ==============================================================================
echo "=== Этап 1: Проверка кода ==="
echo "Пытаемся импортировать приложение..."

# Временный файл для сохранения вывода
import_log=$(mktemp)

# Запускаем проверку с выводом в реальном времени (через tee)
# |& — перенаправляет и stdout, и stderr в pipe
# tee записывает вывод и в файл, и в терминал одновременно
if ! python -c "from src.main import app; print('Импорт успешен')" |& tee "$import_log"; then
    echo ""
    echo "ОШИБКА: Код не прошёл проверку!"

    import_error=$(cat "$import_log")
    error_length=${#import_error}

    if [ $error_length -gt 3500 ]; then
        # Ошибка слишком длинная — отправляем краткое сообщение и файл
        short_message="🚨 <b>Ошибка деплоя: проверка кода</b>

Приложение не смогло импортироваться.
Ошибка слишком длинная — полный лог в файле ниже."

        send_telegram_notification "$short_message"
        send_telegram_file "$import_error" "deploy_error_import.txt"
    else
        # Ошибка короткая — отправляем как текст
        # Экранируем HTML-символы в тексте ошибки, т.к. traceback содержит <, >
        # (например, File "<string>") которые сломают parse_mode=HTML
        escaped_error=$(escape_html "$import_error")
        error_message="🚨 <b>Ошибка деплоя: проверка кода</b>

Приложение не смогло импортироваться.
Скорее всего, есть синтаксическая ошибка или проблема с зависимостями.

<code>${escaped_error}</code>

Проверьте логи в Amvera для деталей."

        send_telegram_notification "$error_message"
    fi

    rm -f "$import_log"
    exit 1
fi

rm -f "$import_log"
echo "✓ Код прошёл проверку"
echo ""

# ==============================================================================
# ЭТАП 2: МИГРАЦИИ БАЗЫ ДАННЫХ
# ==============================================================================
#
# Применяем все накопленные миграции Alembic.
# "alembic upgrade head" — применить все миграции до последней версии.
#
# Что может пойти не так:
#   - Нет подключения к базе данных (timeout)
#   - Конфликт миграций (две ветки с разными миграциями)
#   - Ошибка в коде миграции
#   - База данных уже содержит несовместимые данные
#
# При ошибке миграции приложение НЕ запустится.
# Это защищает от ситуации, когда код ожидает новую схему БД,
# а в базе старая структура.
#
# ВАЖНО: Вывод показывается в реальном времени через tee.
# Таймаут 120 секунд — если миграция зависла, она будет прервана.
# ==============================================================================
echo "=== Этап 2: Миграции базы данных ==="
echo "Применяем миграции (alembic upgrade head)..."
echo ""

# Таймаут на миграции в секундах.
# Если миграция зависла (например, нет подключения к БД) — прерываем через 120 сек.
# Обычные миграции занимают несколько секунд, так что 120 сек — это много.
MIGRATION_TIMEOUT=120

# Временный файл для сохранения вывода
migration_log=$(mktemp)

# Формируем команду миграции.
# На некоторых окружениях (например Render native runtime) утилиты timeout может не быть.
# В таком случае запускаем миграции без timeout, чтобы не падать с "command not found".
if command -v timeout > /dev/null 2>&1; then
    migration_cmd=(timeout "${MIGRATION_TIMEOUT}" alembic upgrade head)
else
    echo "⚠️  Утилита timeout не найдена — запускаем миграции без ограничения по времени"
    migration_cmd=(alembic upgrade head)
fi

# Запускаем миграции и сохраняем лог.
# set +e нужен временно, чтобы вручную обработать код возврата.
set +e
"${migration_cmd[@]}" |& tee "$migration_log"
migration_exit=${PIPESTATUS[0]}
set -e

if [ "$migration_exit" -ne 0 ]; then
    exit_code=$migration_exit
    echo ""

    # Код 124 означает, что timeout прервал команду
    if [ $exit_code -eq 124 ]; then
        echo "ОШИБКА: Миграции зависли (таймаут ${MIGRATION_TIMEOUT} сек)!"
        timeout_message="🚨 <b>Ошибка деплоя: миграции зависли</b>

Миграции не завершились за ${MIGRATION_TIMEOUT} секунд.
Возможные причины:
• Нет подключения к базе данных
• База данных заблокирована
• Слишком долгая миграция данных

Проверьте:
• Доступность PostgreSQL
• Переменные окружения DATABASE__*
• Логи в Amvera"

        send_telegram_notification "$timeout_message"
    else
        echo "ОШИБКА: Миграции не применились!"

        migration_error=$(cat "$migration_log")
        error_length=${#migration_error}

        if [ $error_length -gt 3500 ]; then
            short_message="🚨 <b>Ошибка деплоя: миграции БД</b>

Не удалось применить миграции.
Ошибка слишком длинная — полный лог в файле ниже."

            send_telegram_notification "$short_message"
            send_telegram_file "$migration_error" "deploy_error_migration.txt"
        else
            # Экранируем HTML-символы в тексте ошибки
            escaped_error=$(escape_html "$migration_error")
            error_message="🚨 <b>Ошибка деплоя: миграции БД</b>

Не удалось применить миграции базы данных.
Возможные причины:
• Нет подключения к БД
• Конфликт миграций
• Ошибка в коде миграции

<code>${escaped_error}</code>

Проверьте логи в Amvera для деталей."

            send_telegram_notification "$error_message"
        fi
    fi

    rm -f "$migration_log"
    exit 1
fi

rm -f "$migration_log"
echo ""
echo "✓ Миграции применены успешно"
echo ""

# ==============================================================================
# ЭТАП 3: ЗАПУСК ПРИЛОЖЕНИЯ
# ==============================================================================
#
# Запускаем uvicorn с нашим FastAPI приложением.
#
# exec — заменяет процесс bash на uvicorn.
# Это важно для корректной обработки сигналов:
#   - SIGTERM при остановке контейнера уйдёт напрямую в uvicorn
#   - uvicorn корректно завершит работу (graceful shutdown)
#   - Без exec сигнал ушёл бы в bash, а uvicorn мог бы зависнуть
#
# Параметры uvicorn:
#   --host 0.0.0.0 — слушать на всех интерфейсах (обязательно для контейнера)
#   --port 8000 — порт, указанный в amvera.yml (containerPort: 8000)
#   --proxy-headers — доверять заголовкам X-Forwarded-* от прокси
#   --forwarded-allow-ips="*" — принимать заголовки от любого IP прокси
#
# ВАЖНО: --proxy-headers и --forwarded-allow-ips ОБЯЗАТЕЛЬНЫ для работы за прокси!
# Amvera (и большинство PaaS) используют reverse proxy перед вашим приложением.
# Без этих параметров:
#   - Статические файлы SQLAdmin могут не загружаться
#   - URL-ы будут генерироваться с HTTP вместо HTTPS
#   - request.url.scheme всегда будет "http"
# ==============================================================================
echo "=== Этап 3: Запуск приложения ==="
echo "Запускаем uvicorn..."
# Для Render порт приходит в переменной PORT (обычно 10000).
# Для локального запуска оставляем fallback 8000.
exec python -m uvicorn src.main:app --host 0.0.0.0 --port "${PORT:-8000}" --proxy-headers --forwarded-allow-ips="*"
